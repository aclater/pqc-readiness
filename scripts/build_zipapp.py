"""Build dist/pqc-readiness.pyz: the pqc_readiness package as a single
executable zip (stdlib zipapp), for scp-and-run deployment (#80).

Only *.py files from the package are included (no __pycache__), entries
are sorted, and every entry gets a fixed timestamp, so two builds of the
same tree produce byte-identical archives.

    python3 scripts/build_zipapp.py [--output PATH]
"""

from __future__ import annotations

import argparse
import stat
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "pqc_readiness"
SHEBANG = b"#!/usr/bin/env python3\n"
MAIN = (
    "# Generated by scripts/build_zipapp.py: entry point of pqc-readiness.pyz\n"
    "import sys\n\n"
    "from pqc_readiness.cli import main\n\n"
    "sys.exit(main())\n"
)
FIXED_DATE = (2026, 1, 1, 0, 0, 0)


def build(output: Path) -> None:
    sources = sorted(p for p in PACKAGE.rglob("*.py") if "__pycache__" not in p.parts)
    if not sources:
        raise SystemExit(f"no sources under {PACKAGE}")
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp = output.with_suffix(".pyz.tmp")
    with tmp.open("wb") as fh:
        fh.write(SHEBANG)
        with zipfile.ZipFile(fh, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            entries = [("__main__.py", MAIN.encode())]
            entries += [
                (p.relative_to(ROOT).as_posix(), p.read_bytes()) for p in sources
            ]
            for name, data in entries:
                info = zipfile.ZipInfo(name, date_time=FIXED_DATE)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (stat.S_IFREG | 0o644) << 16
                zf.writestr(info, data)
    tmp.chmod(0o755)
    tmp.replace(output)
    print(f"built {output} ({output.stat().st_size} bytes, {len(sources)} modules)")


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--output", type=Path, default=ROOT / "dist" / "pqc-readiness.pyz")
    build(ap.parse_args().output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
